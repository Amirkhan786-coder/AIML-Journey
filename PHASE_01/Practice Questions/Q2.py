print("----OPERATORS----")

print("----Arithmetic Operators----")
a = 10 
b = 3
print("Addition:", a + b)   
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Modulus:", a % b)
print("Exponentiation:", a ** b)

print("----Comparison Operators----")
x = 10 
y = 20
print("Equal:", x == y)
print("Not Equal:", x != y)
print("Greater than:", x > y)
print("Less than:", x < y)  
print("Greater than or equal to:", x >= y)
print("Less than or equal to:", x <= y)

print("----Logical Operators----")
p = True
q = False
print("Logical AND:", p and q)
print("Logical OR:", p or q)    
print("Logical NOT:", not p)

print("----Assignment Operators----")
a = 5
print("Assignment:", a)
print("Add and Assign:", a + 2)
print("Subtract and Assign:", a - 2)
print("Multiply and Assign:", a * 2)
print("Divide and Assign:", a / 2)
print("Modulus and Assign:", a % 2)
print("Exponentiation and Assign:", a ** 2)
print("Floor Division and Assign:", a // 2)

print("----Bitwise Operators----")
x = 5
y = 3
print("Bitwise AND:", x & y)
print("Bitwise OR:", x | y)
print("Bitwise XOR:", x ^ y)
print("Bitwise NOT:", ~x)
print("Left Shift:", x << 1)
print("Right Shift:", x >> 1)   

print("----Membership Operators----")
list1 = [1, 2, 3, 4, 5]
print("Is 3 in list1?", 3 in list1)
print("Is 6 not in list1?", 6 not in list1)
print("Is 2 in list1?", 2 in list1)
print("Is 7 not in list1?", 7 not in list1)
print("Is 1 in list1?", 1 in list1)
print("Is 4 not in list1?", 4 not in list1)
print("Is 5 in list1?", 5 in list1)
print("Is 0 not in list1?", 0 not in list1)


print("----Identity Operators----")
a = 10  
print("Is a identical to 10?", a is 10)
print("Is a not identical to 20?", a is not 20)

